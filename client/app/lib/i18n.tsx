export type MessageKey = keyof typeof uk;

const dictionaries: Record<Locale, Record<MessageKey, string>> = { uk, en };

export function translate(
  locale: Locale,
  key: MessageKey,
  vars?: Record<string, string | number>
) {
  let text = dictionaries[locale][key] ?? dictionaries.uk[key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function readStoredLocale(): Locale {
  if (typeof window === "undefined") return "en";
  try {
    return localStorage.getItem(LANG_KEY) === "uk" ? "uk" : "en";
  } catch {
    return "en";
  }
}

type LocaleContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: MessageKey, vars?: Record<string, string | number>) => string;
};

const LocaleContext = createContext<LocaleContextValue | null>(null);

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("en");

  useEffect(() => {
    setLocaleState(readStoredLocale());
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const value = useMemo<LocaleContextValue>(
    () => ({
      locale,
      setLocale: (next) => {
        setLocaleState(next);
        try {
          localStorage.setItem(LANG_KEY, next);
        } catch {
          // ігноруємо, якщо сховище недоступне
        }
      },
      t: (key, vars) => translate(locale, key, vars),
    }),
    [locale]
  );

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  const ctx = useContext(LocaleContext);
  if (ctx) return ctx;
  return {
    locale: "en" as Locale,
    setLocale: () => {},
    t: (key: MessageKey, vars?: Record<string, string | number>) => translate("en", key, vars),
  };
}
